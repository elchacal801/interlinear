def hermes_db(rows, wal=False, table="messages") -> bytes:
    connection = sqlite3.connect(":memory:")
    connection.execute("CREATE TABLE sessions (id TEXT PRIMARY KEY, source TEXT, started_at REAL)")
    connection.execute(f"CREATE TABLE {table} (id INTEGER PRIMARY KEY AUTOINCREMENT, session_id TEXT, role TEXT, "
                       "content TEXT, tool_call_id TEXT, tool_calls TEXT, tool_name TEXT, timestamp REAL, "
                       "reasoning TEXT, display_identity BLOB)")
    connection.executemany(f"INSERT INTO {table} (session_id, role, content, tool_calls, timestamp, display_identity)"
                           " VALUES (?, ?, ?, ?, ?, ?)", rows)
    connection.commit()
    data = connection.serialize()
    connection.close()
    return data[:18] + bytes((2, 2)) + data[20:] if wal else data


