def _deepest_nesting(template: str) -> int:
    """The deepest [[...]] nesting that json.loads accepts at @N@ in template, on this Python."""
    low, high = 1, 100_000
    while low < high:
        mid = (low + high + 1) // 2
        try:
            json.loads(template.replace("@N@", "[" * mid + "]" * mid))
            low = mid
        except RecursionError:
            high = mid - 1
    return low


