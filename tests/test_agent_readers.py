def test_claude_code_odd_records_are_kept_or_named_never_fatal():
    text = "\n".join([
        "not json",
        json.dumps([1, 2]),
        json.dumps({"type": ["user"], "sessionId": "s"}),
        json.dumps({"type": "user", "message": "text"}),
        json.dumps(cc("assistant", [{"type": "tool_use", "name": {"x": 1}, "input": [1]}, {"type": {"a": 1}}])),
        json.dumps(cc("user", [{"type": "tool_result", "content": {"k": "v"}}, 7])),
        json.dumps({"type": "brand-new-record", "sessionId": "s"}),
        json.dumps(cc("user", "hi") | {"timestamp": "yesterday"}),
        "[" * 100000,
    ])
    commands, warnings = read_claude_code(text)
    assert [c.actor for c in commands] == ["unknown", "unknown", "unknown", "unknown", "agent_tool", "unknown",
                                           "tool_output", "unknown", "unknown", "operator", "unknown"]
    assert commands[4].text == "tool: [1]"
    assert commands[6].text == '{"k": "v"}'
    assert commands[8].text == json.dumps({"type": "brand-new-record", "sessionId": "s"})
    assert any("record type 'brand-new-record' not read" in w for w in warnings)
    assert any("unparseable timestamp 'yesterday'" in w for w in warnings)
    assert any("line 9: not JSON" in w for w in warnings)


