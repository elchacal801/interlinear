def item(payload, ts="2026-10-20T10:00:00.5Z"):
    return {"timestamp": ts, "type": "response_item", "payload": payload}


def call(name, arguments):
    return item({"type": "function_call", "name": name, "arguments": json.dumps(arguments), "call_id": "c"})


