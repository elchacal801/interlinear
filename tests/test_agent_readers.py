def test_sliver_commands_go_to_the_model_not_the_shell_rules(tmp_path):
    path = tmp_path / "history"
    path.write_text(jsonl({"datetime": "2026-10-15T09:00:00Z", "block": "ls"},
                          {"datetime": "2026-10-15T09:00:01Z", "block": "rm C:\\\\Windows\\\\Temp\\\\x.exe"}),
                    encoding="utf-8")
    transcript = Transcript.model_validate(parse_paths([path], now=AT))
